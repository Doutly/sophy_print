import { PDFDocument, rgb, degrees } from "pdf-lib";

export type OrientationMode = "portrait" | "landscape" | "auto";
export type PagesPerSheetMode = 1 | 2 | 4;
export type PageSizingMode = "fit" | "actual" | "scale";
export type DuplexMode = "single" | "duplex-long" | "duplex-short";
export type PaperSizeMode = "A4" | "Letter" | "Legal";
export type PageRangeOption = "all" | "current" | "custom" | "odd" | "even";

export interface PrintLayoutConfig {
  orientation: OrientationMode;
  pagesPerSheet: PagesPerSheetMode;
  pageSizing: PageSizingMode;
  customScalePercent: number; // e.g. 100
  duplex: DuplexMode;
  paperSize: PaperSizeMode;
  pageRangeOption: PageRangeOption;
  customRangeText?: string;
  currentPageNumber?: number;
  reversePages?: boolean;
  autoCenter?: boolean;
  autoRotate?: boolean;
  printContentMode?: "document" | "with-notes";
}

export const DEFAULT_PRINT_LAYOUT_CONFIG: PrintLayoutConfig = {
  orientation: "portrait",
  pagesPerSheet: 1,
  pageSizing: "fit",
  customScalePercent: 100,
  duplex: "single",
  paperSize: "A4",
  pageRangeOption: "all",
  customRangeText: "1",
  currentPageNumber: 1,
  reversePages: false,
  autoCenter: true,
  autoRotate: true,
  printContentMode: "document",
};

export const PAPER_DIMENSIONS_PT: Record<PaperSizeMode, [number, number]> = {
  A4: [595.28, 841.89],
  Letter: [612.0, 792.0],
  Legal: [612.0, 1008.0],
};

/**
 * Filter and resolve zero-based page indices from layout range options
 */
export function resolvePageIndices(
  totalPages: number,
  option: PageRangeOption,
  customRange?: string,
  currentPage: number = 1,
  reverse: boolean = false,
): number[] {
  if (totalPages <= 0) return [];
  let indices: number[] = [];

  if (option === "all") {
    indices = Array.from({ length: totalPages }, (_, i) => i);
  } else if (option === "current") {
    const curZero = Math.max(0, Math.min(currentPage - 1, totalPages - 1));
    indices = [curZero];
  } else if (option === "odd") {
    for (let i = 0; i < totalPages; i += 2) indices.push(i); // Page 1, 3, 5... (0, 2, 4...)
  } else if (option === "even") {
    for (let i = 1; i < totalPages; i += 2) indices.push(i); // Page 2, 4, 6... (1, 3, 5...)
  } else if (option === "custom") {
    const raw = customRange || "1";
    const parts = raw.split(",").map((s) => s.trim()).filter(Boolean);
    const set = new Set<number>();

    for (const part of parts) {
      if (part.includes("-")) {
        const [startStr, endStr] = part.split("-").map((s) => s.trim());
        const start = parseInt(startStr || "", 10);
        const end = parseInt(endStr || "", 10);
        if (!isNaN(start) && !isNaN(end)) {
          const from = Math.max(1, Math.min(start, end));
          const to = Math.min(totalPages, Math.max(start, end));
          for (let p = from; p <= to; p++) set.add(p - 1);
        }
      } else {
        const pageNum = parseInt(part, 10);
        if (!isNaN(pageNum) && pageNum >= 1 && pageNum <= totalPages) {
          set.add(pageNum - 1);
        }
      }
    }
    indices = Array.from(set).sort((a, b) => a - b);
    if (indices.length === 0) indices = [0];
  }

  if (reverse) {
    indices = [...indices].reverse();
  }

  return indices;
}

/**
 * Calculates total billable physical paper sheets and sides
 */
export function computeSheetMetrics(
  selectedPageCount: number,
  pagesPerSheet: PagesPerSheetMode,
  duplex: DuplexMode,
): { printedFaces: number; physicalSheets: number; isDuplex: boolean } {
  if (selectedPageCount <= 0) {
    return { printedFaces: 0, physicalSheets: 0, isDuplex: false };
  }

  // How many sheet faces (pages of print) are generated by N-up
  const printedFaces = Math.ceil(selectedPageCount / pagesPerSheet);

  const isDuplex = duplex !== "single";
  // If double-sided, each physical sheet holds up to 2 faces (front & back)
  const physicalSheets = isDuplex ? Math.ceil(printedFaces / 2) : printedFaces;

  return {
    printedFaces,
    physicalSheets,
    isDuplex,
  };
}

/**
 * Transforms a source PDF document applying orientation, scale, and N-up sheet grids
 */
export async function transformPdfLayout(
  sourceBytes: ArrayBuffer | Uint8Array,
  config: PrintLayoutConfig,
  baseFileName: string = "Document.pdf",
): Promise<{
  transformedBytes: Uint8Array;
  sheetCount: number;
  outputFileName: string;
}> {
  const sourceDoc = await PDFDocument.load(sourceBytes, { ignoreEncryption: true });
  const totalPages = sourceDoc.getPageCount();

  const selectedIndices = resolvePageIndices(
    totalPages,
    config.pageRangeOption,
    config.customRangeText,
    config.currentPageNumber || 1,
    config.reversePages || false,
  );

  if (selectedIndices.length === 0) {
    throw new Error("No pages selected for printing.");
  }

  const [paperW, paperH] = PAPER_DIMENSIONS_PT[config.paperSize] || PAPER_DIMENSIONS_PT.A4;
  const isLandscape = config.orientation === "landscape";
  const targetSheetWidth = isLandscape ? paperH : paperW;
  const targetSheetHeight = isLandscape ? paperW : paperH;

  const targetDoc = await PDFDocument.create();

  // Standard margin on sheet (18pt = 0.25 inch)
  const margin = 18;
  const usableWidth = targetSheetWidth - margin * 2;
  const usableHeight = targetSheetHeight - margin * 2;

  // N-up grouping: slice selected pages into groups of 1, 2, or 4
  const nUp = config.pagesPerSheet;
  const pageChunks: number[][] = [];
  for (let i = 0; i < selectedIndices.length; i += nUp) {
    pageChunks.push(selectedIndices.slice(i, i + nUp));
  }

  const sourcePages = sourceDoc.getPages();
  // Ensure any blank source page without content stream can be safely embedded
  for (const page of sourcePages) {
    if (!page.node.Contents()) {
      page.drawText(" ", { size: 1, x: 0, y: 0 });
    }
  }

  // Embed source pages into target document
  for (const chunk of pageChunks) {
    const sheet = targetDoc.addPage([targetSheetWidth, targetSheetHeight]);

    if (nUp === 1) {
      // 1-on-1 Full Page placement
      const pageIndex = chunk[0]!;
      const embedded = await targetDoc.embedPage(sourcePages[pageIndex]!);
      const { width: origW, height: origH } = embedded;

      let scale = 1.0;
      if (config.pageSizing === "fit") {
        const scaleX = usableWidth / origW;
        const scaleY = usableHeight / origH;
        scale = Math.min(scaleX, scaleY);
      } else if (config.pageSizing === "scale") {
        scale = (config.customScalePercent || 100) / 100;
      }

      const drawW = origW * scale;
      const drawH = origH * scale;
      const x = config.autoCenter ? margin + (usableWidth - drawW) / 2 : margin;
      const y = config.autoCenter ? margin + (usableHeight - drawH) / 2 : margin + (usableHeight - drawH);

      sheet.drawPage(embedded, {
        x,
        y,
        width: drawW,
        height: drawH,
      });
    } else if (nUp === 2) {
      // 2-on-1: Two pages side-by-side (columns = 2, rows = 1)
      const colWidth = usableWidth / 2 - 8;
      const rowHeight = usableHeight;
      const gap = 16;

      for (let slot = 0; slot < chunk.length; slot++) {
        const pageIdx = chunk[slot]!;
        const embedded = await targetDoc.embedPage(sourcePages[pageIdx]!);
        const { width: origW, height: origH } = embedded;

        const scaleX = colWidth / origW;
        const scaleY = rowHeight / origH;
        const scale = Math.min(scaleX, scaleY);

        const drawW = origW * scale;
        const drawH = origH * scale;

        const slotX = margin + slot * (colWidth + gap);
        const x = slotX + (colWidth - drawW) / 2;
        const y = margin + (rowHeight - drawH) / 2;

        sheet.drawPage(embedded, {
          x,
          y,
          width: drawW,
          height: drawH,
        });

        // Thin subtle slot border
        sheet.drawRectangle({
          x: slotX,
          y: margin,
          width: colWidth,
          height: rowHeight,
          borderWidth: 0.5,
          borderColor: rgb(0.85, 0.85, 0.85),
          opacity: 0.4,
        });
      }
    } else if (nUp === 4) {
      // 4-on-1 (2x2 grid): Two columns, two rows
      const colWidth = usableWidth / 2 - 8;
      const rowHeight = usableHeight / 2 - 8;
      const gapX = 16;
      const gapY = 16;

      for (let slot = 0; slot < chunk.length; slot++) {
        const pageIdx = chunk[slot]!;
        const embedded = await targetDoc.embedPage(sourcePages[pageIdx]!);
        const { width: origW, height: origH } = embedded;

        const col = slot % 2; // 0 or 1
        const row = Math.floor(slot / 2); // 0 (top) or 1 (bottom)

        const scaleX = colWidth / origW;
        const scaleY = rowHeight / origH;
        const scale = Math.min(scaleX, scaleY);

        const drawW = origW * scale;
        const drawH = origH * scale;

        const slotX = margin + col * (colWidth + gapX);
        // In PDF coordinates, Y=0 is bottom
        const slotY = margin + (1 - row) * (rowHeight + gapY);

        const x = slotX + (colWidth - drawW) / 2;
        const y = slotY + (rowHeight - drawH) / 2;

        sheet.drawPage(embedded!, {
          x,
          y,
          width: drawW,
          height: drawH,
        });

        // Thin subtle slot border
        sheet.drawRectangle({
          x: slotX,
          y: slotY,
          width: colWidth,
          height: rowHeight,
          borderWidth: 0.5,
          borderColor: rgb(0.85, 0.85, 0.85),
          opacity: 0.4,
        });
      }
    }
  }

  const transformedBytes = await targetDoc.save();
  const cleanBase = baseFileName.replace(/\.pdf$/i, "").replace(/[^a-zA-Z0-9.-]/g, "_");
  const layoutSuffix = `${config.orientation}_${config.pagesPerSheet}up_${config.duplex}`;
  const outputFileName = `${cleanBase}_${layoutSuffix}.pdf`;

  return {
    transformedBytes,
    sheetCount: targetDoc.getPageCount(),
    outputFileName,
  };
}
